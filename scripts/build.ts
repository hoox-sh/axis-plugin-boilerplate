/**
 * Bundle TypeScript plugins to browser ESM under `public/`.
 * AXIS dynamic-imports these files via URL.
 */

import { mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";

const root = join(import.meta.dir, "..");

const entries = [
  { in: "src/plugin.ts", out: "public/plugin.js" },
  { in: "src/examples/source.ts", out: "public/examples/source.js" },
  { in: "src/examples/stream.ts", out: "public/examples/stream.js" },
  { in: "src/examples/engine.ts", out: "public/examples/engine.js" },
  { in: "src/examples/dataset.ts", out: "public/examples/dataset.js" },
  { in: "src/examples/component.ts", out: "public/examples/component.js" },
] as const;

const banner = [
  "// AXIS plugin — pynescript.axis.plugins.v1",
  "// Generated by `bun run build`. Edit the TypeScript under src/, not this file.",
  "",
].join("\n");

await mkdir(join(root, "public/examples"), { recursive: true });

for (const entry of entries) {
  const result = await Bun.build({
    entrypoints: [join(root, entry.in)],
    format: "esm",
    target: "browser",
    minify: false,
    sourcemap: "none",
  });
  if (!result.success) {
    const msgs = result.logs.map((l) => String(l)).join("\n");
    throw new Error(`build failed for ${entry.in}:\n${msgs}`);
  }
  const artifact = result.outputs[0];
  if (!artifact) throw new Error(`build produced no output for ${entry.in}`);
  const js = `${banner}${await artifact.text()}`;
  const dest = join(root, entry.out);
  await mkdir(dirname(dest), { recursive: true });
  await Bun.write(dest, js);
  console.log(`  ${entry.in} → ${entry.out}`);
}

console.log(`built ${entries.length} module(s)`);
